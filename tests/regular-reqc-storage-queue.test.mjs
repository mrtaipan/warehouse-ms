import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const ids = {
  mob: '10000000-0000-0000-0000-000000000001',
  oi: '10000000-0000-0000-0000-000000000002',
  mobResult: '20000000-0000-0000-0000-000000000001',
  oiResult: '20000000-0000-0000-0000-000000000002',
}

test('Re-QC Grade A enters Storage Queue and is stored exactly once in a matching group', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create function reqc_has_permission(text) returns boolean language sql as $$ select true $$;
      create table reqc_queue (
        id uuid primary key, group_code text, sku_id text, source_variant_code text,
        item_name text, size text, category_id bigint, brand_code text
      );
      create table reqc_results (
        id uuid primary key, reqc_queue_id uuid references reqc_queue(id),
        grade text, qty integer, status text default 'PENDING_REVIEW',
        reviewed_by text, reviewed_at timestamptz, updated_at timestamptz,
        constraint reqc_results_status_check check (status in ('PENDING_REVIEW', 'SHELVING_QUEUE', 'REJECTION_STORAGE'))
      );
      create table dir_rack_locations (
        id bigint primary key, group_code text, location_type text
      );
      create table warehouse_storage (
        id bigint generated by default as identity primary key,
        rack_location_id bigint references dir_rack_locations(id),
        sku_id text, source_variant_code text, item_name text, size text,
        category_id bigint, brand_code text, qty integer, notes text, updated_by text
      );
      create function confirm_reqc_grade_a_to_shelving(uuid, text) returns uuid
        language sql as $$ select $1 $$;
      insert into reqc_queue values
        ('${ids.mob}', 'MOB', 'MOB-1', 'MOB-1', 'MOB shirt', 'L', 10, 'MOB'),
        ('${ids.oi}', 'OI', 'OI-1', 'OI-1', 'OI shirt', 'M', 11, 'OI');
      insert into reqc_results (id, reqc_queue_id, grade, qty, status) values
        ('${ids.mobResult}', '${ids.mob}', 'A', 5, 'PENDING_REVIEW'),
        ('${ids.oiResult}', '${ids.oi}', 'A', 3, 'PENDING_REVIEW');
      insert into dir_rack_locations values
        (1, 'MOB', 'PALLET'), (2, 'OI', 'PALLET'), (3, 'MOB', 'SHELVING');
    `)

    const migration = await readFile(new URL('../supabase/regular_reqc_storage_queue.sql', import.meta.url), 'utf8')
    await db.exec(migration)

    await db.query('select confirm_reqc_grade_a_to_storage($1, $2)', [ids.mobResult, 'reviewer'])
    await db.query('select confirm_reqc_grade_a_to_storage($1, $2)', [ids.oiResult, 'reviewer'])
    await assert.rejects(db.query('select confirm_reqc_grade_a_to_storage($1, $2)', [ids.mobResult, 'reviewer']), /already been reviewed/)
    await assert.rejects(db.query('select store_reqc_grade_a_results($1::uuid[], $2, $3, $4)', [[ids.mobResult], 3, 'storer', null]), /pallet storage location/)
    await assert.rejects(db.query('select store_reqc_grade_a_results($1::uuid[], $2, $3, $4)', [[ids.mobResult, ids.oiResult], 1, 'storer', null]), /does not match the selected storage group/)
    assert.equal((await db.query('select count(*)::int as count from warehouse_storage')).rows[0].count, 0)

    const stored = await db.query('select store_reqc_grade_a_results($1::uuid[], $2, $3, $4) as count', [[ids.mobResult], 1, 'storer', 'Checked'])
    assert.equal(stored.rows[0].count, 1)
    const stock = await db.query('select reqc_result_id, qty, rack_location_id, notes from warehouse_storage')
    assert.deepEqual(stock.rows, [{ reqc_result_id: ids.mobResult, qty: 5, rack_location_id: 1, notes: 'Checked' }])
    assert.equal((await db.query('select status from reqc_results where id = $1', [ids.mobResult])).rows[0].status, 'STORED')
    assert.equal((await db.query('select status from reqc_results where id = $1', [ids.oiResult])).rows[0].status, 'STORAGE_QUEUE')
    await assert.rejects(db.query('select store_reqc_grade_a_results($1::uuid[], $2, $3, $4)', [[ids.mobResult], 1, 'storer', null]), /not waiting in Storage Queue/)
  } finally {
    await db.close()
  }
})
