import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

test('Reguler Re-QC reject review requires a note and stores it once', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create function reqc_has_permission(text) returns boolean language sql as $$ select true $$;
      create table reqc_queue (id uuid primary key, category_id bigint, item_name text, size text);
      create table reqc_results (
        id uuid primary key, reqc_queue_id uuid, grade text, qty integer,
        status text, reviewed_by text, reviewed_at timestamptz, updated_at timestamptz
      );
      create table dir_categories (id bigint primary key, parent_id bigint, level integer);
      create table warehouse_reject_storage (
        id bigint generated by default as identity primary key, koli_number text,
        product_name text, size text, category_id bigint, sub_category_id bigint,
        item_type_id bigint, qty integer, grade text, reject_note text,
        status text, created_by text, updated_by text, reqc_result_id uuid
      );
      create function next_warehouse_reject_koli_number() returns text language sql as $$ select 'R-001' $$;
      create function confirm_reqc_reject_to_storage(uuid, text, text) returns bigint language sql as $$ select 1::bigint $$;
      insert into dir_categories values (1, null, 1), (2, 1, 2), (3, 2, 3);
      insert into reqc_queue values ('10000000-0000-0000-0000-000000000001', 3, 'Shirt', 'L');
      insert into reqc_results values ('20000000-0000-0000-0000-000000000001', '10000000-0000-0000-0000-000000000001', 'C', 4, 'PENDING_REVIEW', null, null, null);
    `)
    const migration = await readFile(new URL('../supabase/regular_reqc_reject_note.sql', import.meta.url), 'utf8')
    await db.exec(migration)

    const args = ['20000000-0000-0000-0000-000000000001', null, '', 'reviewer']
    await assert.rejects(db.query('select confirm_reqc_reject_to_storage_with_note($1, $2, $3, $4)', args), /Enter a reject note/)
    args[2] = ' Torn seam '
    const stored = await db.query('select confirm_reqc_reject_to_storage_with_note($1, $2, $3, $4) as id', args)
    assert.equal(stored.rows[0].id, 1)
    assert.deepEqual((await db.query('select koli_number, qty, grade, reject_note from warehouse_reject_storage')).rows,
      [{ koli_number: 'R-001', qty: 4, grade: 'C', reject_note: 'Torn seam' }])
    assert.equal((await db.query('select status from reqc_results')).rows[0].status, 'REJECTION_STORAGE')
    await assert.rejects(db.query('select confirm_reqc_reject_to_storage_with_note($1, $2, $3, $4)', args), /already been reviewed/)
    assert.equal((await db.query("select has_function_privilege('authenticated', 'confirm_reqc_reject_to_storage(uuid,text,text)', 'EXECUTE') as allowed")).rows[0].allowed, false)
  } finally {
    await db.close()
  }
})
