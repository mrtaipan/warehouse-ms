async function isolated(fn) {
  await db.exec('begin;')
  try { await fn() } finally { await db.exec('rollback;') }
}

async function addCase(id, group, replacement = null, sku = 'ARK01SSP002', size = 'S') {
  await db.query(`insert into delivery_error_retur_cases (id,kode_kejadian,group_order,status_barang,produk_diretur,produk_pengganti) values ($1,$2,$3,'Sending',$4,$5)`,
    [id, `TEST-${id}`, group, `SKU: ${sku} || PRODUCT: RETURN ITEM || SIZE: ${size} || QTY: 2`, replacement])
  return [{ case_id: id, lines: [{ sku, product_name: 'RETURN ITEM', size, expected_qty: 2, stored_qty: 2, reject_qty: 0, lost_qty: 0 }] }]
}
const complete = (payload) => db.query('select complete_delivery_return_cases($1::jsonb)', [JSON.stringify(payload)])

await test('SQL matches paired upload sizes and old saved S + raw S/95', async () => {
  assert.equal(await scalar("select warehouse_sizes_match('95','S/95')"), true)
  assert.equal(await scalar("select warehouse_sizes_match('95','S','S/95')"), true)
  assert.equal(await scalar("select warehouse_sizes_match('100','S','S/95')"), false)
  assert.equal(await scalar("select warehouse_sizes_match('95','S')"), false)
  assert.equal(await scalar("select warehouse_sizes_match('32','32/30')"), false)
})

await test('indexed SKU tokens preserve legacy matching through SKU, variant or product name', () => isolated(async () => {
  assert.equal(await scalar("select upload_stock_sku_tokens('KOL01SST001-001',null,'SHIRT') @> array['KOL01SST001001']"), true)
  assert.equal(await scalar("select upload_stock_sku_tokens(null,'KOL01SST001-001','SHIRT') @> array['KOL01SST001001']"), true)
  assert.equal(await scalar("select upload_stock_sku_tokens(null,null,'KOL01SST001-001 | SHIRT') @> array['KOL01SST001001']"), true)
  assert.equal(await scalar("select upload_stock_sku_tokens('KOL01SST001-002',null,'SHIRT') @> array['KOL01SST001001']"), false)
  await db.exec('set local enable_seqscan = off;')
  const plan = await db.query("explain select id from warehouse_storage where coalesce(qty,0)>0 and upload_stock_sku_tokens(sku_id,source_variant_code,item_name) @> array['KOL01SST001001']")
  assert.match(JSON.stringify(plan.rows), /warehouse_storage_upload_sku_tokens_idx/)
}))

await test('Arkline return adds to an existing dedicated zero shelf and prevents a second completion', () => isolated(async () => {
  await db.exec("insert into dir_rack_locations values (1,'ARKLINE','SHELVING','A9','7','A',null); insert into warehouse_storage (id,rack_location_id,sku_id,item_name,size,qty) values (1,1,'ARK01SSP002','RETURN ITEM','S',0);")
  const payload = await addCase(1, 'ARKLINE')
  await complete(payload)
  assert.equal(await scalar('select qty from warehouse_storage where id=1'), 2)
  assert.equal(await scalar('select count(*)::int from warehouse_shelving_queue'), 0)
  assert.equal(await scalar('select route_status from delivery_return_items'), 'STORED')
  assert.equal(await scalar('select stock_applied_at is not null from delivery_error_retur_cases'), true)
  await db.exec('savepoint duplicate;')
  await assert.rejects(complete(payload), /no longer Sending/)
  await db.exec('rollback to duplicate;')
  assert.equal(await scalar('select qty from warehouse_storage where id=1'), 2)
}))

