test('priority case creates one linked request per replacement line and reconciles edits', async () => {
  await db.exec(`
    insert into delivery_error_retur_cases
      (id, kode_kejadian, created_by, group_order, status_barang, need_prioritized, produk_pengganti)
    values (101, 'AX-101', 'Customer Service', 'MOB', 'Sending', true,
      E'SKU: MOB001 || PRODUCT: Shirt || SIZE: M || QTY: 2\\nSKU: MOB002 || PRODUCT: Pants || SIZE: L || QTY: 1');
  `)
  assert.equal(await scalar("select count(*) from restock_request where return_case_id=101 and request_status='open'"), 2)
  assert.equal(await scalar("select destination_area from restock_request where return_case_id=101 limit 1"), 'RETUR_KEEPING')
  const linkedRequestId = await scalar('select id from restock_request where return_case_id=101 and return_line_no=1')
  await assert.rejects(
    () => db.query('update restock_request set qty=99 where id=$1', [linkedRequestId]),
    /Edit the return case/
  )
  await assert.rejects(
    () => db.query("update restock_request set request_status='completed' where id=$1", [linkedRequestId]),
    /Use priority return completion/
  )
  await db.exec("update delivery_error_retur_cases set produk_pengganti = replace(produk_pengganti, 'QTY: 2', 'QTY: 3') where id=101;")
  assert.equal(await scalar('select qty from restock_request where return_case_id=101 and return_line_no=1'), 3)
  await db.exec('update delivery_error_retur_cases set need_prioritized=false where id=101;')
  assert.equal(await scalar("select count(*) from restock_request where return_case_id=101 and request_status='cancelled'"), 2)
  await db.exec('update delivery_error_retur_cases set need_prioritized=true where id=101;')
  assert.equal(await scalar("select count(*) from restock_request where return_case_id=101 and request_status='open'"), 2)
})

test('source choices include matching pallet, shelving, and Temp. Sales only', async () => {
  await db.exec(`
    insert into dir_rack_locations values
      (1,'MOB','PALLET','LV85','1','K1'),
      (2,'MOB','SHELVING','A','1','A'),
      (3,'OI','PALLET','LV85','2','K1');
    insert into warehouse_storage (id,rack_location_id,sku_id,item_name,size,qty)
    values (1,1,'MOB001','Shirt','M',4),
      (2,2,'MOB001','Shirt','M',3),
      (3,3,'MOB001','Shirt','M',5),
      (4,1,'MOB001','Shirt','L',8);
    insert into warehouse_temporary_sales_items
      (id,sku_id,item_name,size,group_code,area_type,qty_in_area,status)
    values (10,'MOB001','Shirt','M','MOB','SALES',2,'IN_TEMPORARY_AREA'),
      (11,'MOB001','Shirt','M','MOB','RETUR_KEEPING',4,'IN_TEMPORARY_AREA');
  `)
  const requestId = await scalar('select id from restock_request where return_case_id=101 and return_line_no=1')
  const options = await scalar(`select priority_return_source_options('${requestId}')`)
  assert.deepEqual(options.map((option) => option.source_kind).sort(), ['TEMP_SALES', 'WAREHOUSE', 'WAREHOUSE'])
  assert.deepEqual(options.filter((option) => option.source_kind === 'WAREHOUSE').map((option) => Number(option.source_id)).sort(), [1, 2])
  await db.exec("update warehouse_temporary_sales_items set qty_in_area=0,status='COMPLETED' where id=11")
})

test('completion from pallet stages stock once and Resolve consumes Retur Keeping first', async () => {
  const requestId = await scalar('select id from restock_request where return_case_id=101 and return_line_no=1')
  await db.query('select complete_priority_return_restock_request($1, $2, $3, $4)', [requestId, 'WAREHOUSE', 1, 2])
  assert.equal(await scalar('select qty from warehouse_storage where id=1'), 2)
  assert.equal(Number(await scalar(`select qty_in_area from warehouse_temporary_sales_items where restock_request_id='${requestId}'`)), 2)
  assert.equal(await scalar(`select request_status from restock_request where id='${requestId}'`), 'completed')
  await assert.rejects(() => db.query('select complete_priority_return_restock_request($1, $2, $3, $4)', [requestId, 'WAREHOUSE', 1, 1]), /already been handled/)

  await db.query('select complete_delivery_return_cases($1::jsonb)', [JSON.stringify([{ case_id: 101, lines: [] }])])
  assert.equal(Number(await scalar(`select qty_in_area from warehouse_temporary_sales_items where restock_request_id='${requestId}'`)), 0)
  assert.equal(Number(await scalar('select qty_in_area from warehouse_temporary_sales_items where id=10')), 1)
  assert.equal(await scalar("select count(*) from warehouse_storage_movements where movement_type='CUSTOMER_REPLACEMENT_OUT' and from_location_label='TEMP. RETUR KEEPING'"), 1)
  assert.equal(await scalar("select request_status from restock_request where return_case_id=101 and return_line_no=2"), 'cancelled')
})

