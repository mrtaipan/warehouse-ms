test('a mismatched source or insufficient quantity leaves the request and stock unchanged', async () => {
  await db.exec(`
    insert into delivery_error_retur_cases
      (id,kode_kejadian,created_by,group_order,status_barang,need_prioritized,produk_pengganti)
    values (103,'AX-103','Customer Service','MOB','Sending',true,
      'SKU: MOB001 || PRODUCT: Shirt || SIZE: M || QTY: 1');
  `)
  const requestId = await scalar('select id from restock_request where return_case_id=103')
  await assert.rejects(
    () => db.query('select complete_priority_return_restock_request($1,$2,$3,$4)', [requestId, 'WAREHOUSE', 3, 1]),
    /no longer available/
  )
  await assert.rejects(
    () => db.query('select complete_priority_return_restock_request($1,$2,$3,$4)', [requestId, 'WAREHOUSE', 1, 99]),
    /no longer available/
  )
  assert.equal(await scalar(`select request_status from restock_request where id='${requestId}'`), 'open')
  assert.equal(await scalar('select qty from warehouse_storage where id=1'), 2)
  assert.equal(await scalar(`select count(*) from warehouse_temporary_sales_items where restock_request_id='${requestId}'`), 0)
})

