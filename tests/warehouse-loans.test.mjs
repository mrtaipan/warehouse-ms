import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

test('partial PL loan preserves the Packing List and returns only after receipt', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select '00000000-0000-0000-0000-000000000001'::uuid $$;
      create function auth.jwt() returns jsonb language sql stable as $$
        select '{"email":"borrower@example.com"}'::jsonb $$;
      create function reqc_has_permission(p_code text) returns boolean language sql stable as $$ select true $$;
      create function upload_stock_sku_tokens(p_sku text,p_variant text,p_name text) returns text[]
        language sql stable as $$ select array[upper(regexp_replace(coalesce(p_sku,p_variant,''),'[^A-Z0-9]','','g'))] $$;
      create table dir_categories(id bigint primary key);
      create table warehouse_storage(id bigint generated by default as identity primary key,
        rack_location_id bigint,source_pl_packing_item_id bigint,sku_id text,source_variant_code text,item_name text,size text,
        category_id bigint,brand_code text,qty integer,notes text,updated_by text,updated_at timestamptz);
      create table pl_packing_items(id bigint primary key,storage_status text,storing_type text,
        source_variant_code text,size_label text,qty integer);
      create table dir_rack_locations(id bigint primary key,group_code text,location_type text,
        location_name text,location_code text,location_id text,sub_location text);
      create table arkline_dir_products(sku_induk text,is_active boolean);
      create table warehouse_temporary_sales_items(id bigint generated by default as identity primary key,
        source_pl_packing_item_id bigint,sku_id text,source_variant_code text,item_name text,size text,category_id bigint,group_code text,
        area_type text,source_location_label text,qty_in_area integer,status text,created_by text);
      create table warehouse_shelving_queue(id bigint generated by default as identity primary key,
        sku_id text,source_variant_code text,item_name text,size text,group_code text,
        qty integer,status text,notes text,created_by text);
      create table reqc_queue(id uuid primary key default gen_random_uuid(),sku_id text,source_variant_code text,
        item_name text,size text,category_id bigint,brand_code text,group_code text,qty integer,status text,notes text,created_by text);
      create table reqc_results(id uuid primary key,reqc_queue_id uuid,grade text,qty integer,status text,
        reviewed_by text,reviewed_at timestamptz,updated_at timestamptz);
      create function confirm_reqc_grade_a_to_storage(p_result_id uuid,p_confirmed_by text)
        returns uuid language sql as $$ select p_result_id $$;
      create table arkline_qc_rejection_storage_batches(id uuid primary key default gen_random_uuid(),
        storage_number text,sku_induk text,model_name_snapshot text,round_number integer,storage_date date,
        stored_qty integer,source_type text,notes text,created_by text);
      create table arkline_qc_rejection_storage_lines(id uuid primary key default gen_random_uuid(),
        storage_batch_id uuid,reason_snapshot text,grade text,size text,qty integer);
      create table warehouse_storage_movements(id bigint generated by default as identity primary key,
        warehouse_storage_id bigint,movement_type text,qty integer,from_location_label text,
        to_location_label text,item_name text,size text,sku_id text,created_by text);
      insert into pl_packing_items values(7,'queued','MOB','SKU-1','M',10);
      insert into dir_rack_locations(id,group_code,location_type,location_name,location_code,location_id)
        values(1,'MOB','SHELVING','Shelf A','A1','Warehouse LV 83');
    `)
    const sizeSql = await readFile(new URL('../supabase/warehouse_stock_size_matching.sql', import.meta.url), 'utf8')
    await db.exec(sizeSql)
    const loanSql = await readFile(new URL('../supabase/warehouse_loans.sql', import.meta.url), 'utf8')
    await db.exec(loanSql)
    const created = await db.query(`select create_warehouse_loan('MOB','Photoshoot',
      '[{"sku":"SKU-1","name":"Shirt","size":"M","qty":3}]'::jsonb) as id`)
    const loanId = created.rows[0].id
    const item = await db.query(`select id from warehouse_loan_items where loan_id=$1 and event_type='REQUEST'`, [loanId])
    const itemId = item.rows[0].id
    await db.query(`select issue_warehouse_loan_item($1,'PL_QUEUE',7,3)`, [itemId])
    const pl = await db.query('select qty,storage_status from pl_packing_items where id=7')
    assert.deepEqual(pl.rows[0], { qty: 10, storage_status: 'queued' })
    const available = await db.query(`select p.qty-coalesce(sum(i.qty),0) as remaining
      from pl_packing_items p left join warehouse_loan_items i
      on i.source_pl_packing_item_id=p.id and i.event_type='ISSUE' where p.id=7 group by p.id`)
    assert.equal(Number(available.rows[0].remaining), 7)
    const declaration = await db.query('select declare_warehouse_loan_return($1,2) as id', [itemId])
    const tempBefore = await db.query('select count(*)::integer as n from warehouse_temporary_sales_items')
    assert.equal(tempBefore.rows[0].n, 0)
    await db.query(`select receive_warehouse_loan_return($1,2,'TEMP_SALES',null)`, [declaration.rows[0].id])
    const tempAfter = await db.query('select qty_in_area,status from warehouse_temporary_sales_items')
    assert.deepEqual(tempAfter.rows[0], { qty_in_area: 2, status: 'IN_TEMPORARY_AREA' })
    await db.query(`select close_warehouse_loan_item($1,1,'LOST','Lost during shoot')`, [itemId])
    const loan = await db.query('select status from warehouse_loans where id=$1', [loanId])
    assert.equal(loan.rows[0].status, 'CLOSED')
    const plAfter = await db.query('select qty from pl_packing_items where id=7')
    assert.equal(plAfter.rows[0].qty, 10)

    const second = await db.query(`select create_warehouse_loan('MOB','Content',
      '[{"sku":"SKU-1","name":"Shirt","size":"M","qty":2}]'::jsonb) as id`)
    const secondItem = await db.query(`select id from warehouse_loan_items where loan_id=$1 and event_type='REQUEST'`, [second.rows[0].id])
    await db.query(`select issue_warehouse_loan_item($1,'PL_QUEUE',7,2)`, [secondItem.rows[0].id])
    const returnDeclaration = await db.query('select declare_warehouse_loan_return($1,2) as id', [secondItem.rows[0].id])
    const queueReturn = await db.query(`select receive_warehouse_loan_return($1,2,'STORAGE_QUEUE',null) as id`, [returnDeclaration.rows[0].id])
    await db.query(`select place_warehouse_loan_queue_return($1,1,'STORAGE',1)`, [queueReturn.rows[0].id])
    await db.query(`select place_warehouse_loan_queue_return($1,1,'TEMP_SALES',null)`, [queueReturn.rows[0].id])
    const queuePlaced = await db.query(`select sum(qty)::integer as placed from warehouse_loan_items where queue_return_id=$1`, [queueReturn.rows[0].id])
    assert.equal(queuePlaced.rows[0].placed, 2)
    await assert.rejects(() => db.query(`select place_warehouse_loan_queue_return($1,1,'STORAGE',1)`, [queueReturn.rows[0].id]), /exceeds available queue return/)
    const finalPl = await db.query('select qty from pl_packing_items where id=7')
    assert.equal(finalPl.rows[0].qty, 10)

    await db.exec(`
      insert into dir_categories values(42);
      insert into dir_rack_locations(id,group_code,location_type,location_name,location_code,location_id,sub_location)
        values(2,'ARKLINE','SHELVING','A8.6.A','A8.6','Warehouse LV 83','A');
      insert into arkline_dir_products values('ARK01HDO042',true);
      insert into warehouse_storage(rack_location_id,sku_id,source_variant_code,item_name,size,category_id,brand_code,qty)
        values(2,'ARK01HDO042','ARK01HDO042','Sovereign Hoodie','S',42,'ARKLINE',5);
    `)
    const arkline = await db.query(`select create_warehouse_loan('ARKLINE','Photoshoot',
      '[{"sku":"ARK01HDO042","name":"Sovereign Hoodie","size":"S","qty":4}]'::jsonb) as id`)
    const arklineItem = await db.query(`select id from warehouse_loan_items where loan_id=$1 and event_type='REQUEST'`, [arkline.rows[0].id])
    const stock = await db.query('select id from warehouse_storage where sku_id=$1', ['ARK01HDO042'])
    await db.query(`select issue_warehouse_loan_item($1,'STORAGE',$2,3)`, [arklineItem.rows[0].id, stock.rows[0].id])
    assert.equal((await db.query('select qty from warehouse_storage where id=$1', [stock.rows[0].id])).rows[0].qty, 2)
    await db.query('select cancel_warehouse_loan_request_item($1,1)', [arklineItem.rows[0].id])
    const arklineDeclaration = await db.query('select declare_warehouse_loan_return($1,3) as id', [arklineItem.rows[0].id])
    await db.query(`select receive_warehouse_loan_return($1,2,'STORAGE',2)`, [arklineDeclaration.rows[0].id])
    assert.deepEqual((await db.query(`select category_id,brand_code,qty from warehouse_storage
      where notes like 'Returned from loan%'`)).rows.at(-1), { category_id: 42, brand_code: 'ARKLINE', qty: 2 })
    await db.query(`select receive_warehouse_loan_return($1,1,'RE_QC',null)`, [arklineDeclaration.rows[0].id])
    const qcQueue = await db.query('select id,group_code,source_loan_receive_id from reqc_queue')
    assert.equal(qcQueue.rows[0].group_code, 'ARKLINE')
    assert.ok(qcQueue.rows[0].source_loan_receive_id)
    await db.query(`insert into reqc_results(id,reqc_queue_id,grade,qty,status)
      values(gen_random_uuid(),$1,'C',1,'PENDING_REVIEW')`, [qcQueue.rows[0].id])
    const rejectResult = await db.query('select id from reqc_results')
    await db.query(`select review_arkline_loan_reqc_results(array[$1]::uuid[],'STORE_REJECT','Damaged on return')`, [rejectResult.rows[0].id])
    const arklineReject = await db.query(`select b.source_type,l.grade,l.qty from arkline_qc_rejection_storage_batches b
      join arkline_qc_rejection_storage_lines l on l.storage_batch_id=b.id`)
    assert.deepEqual(arklineReject.rows[0], { source_type: 'LOAN_RE_QC', grade: 'C', qty: 1 })
    assert.equal((await db.query('select status from warehouse_loans where id=$1', [arkline.rows[0].id])).rows[0].status, 'COMPLETED')
    const movements = await db.query(`select movement_type,qty from warehouse_storage_movements order by id`)
    assert.deepEqual(movements.rows.map((row) => row.movement_type), ['LOAN_RETURN', 'LOAN_OUT', 'LOAN_RETURN'])
  } finally {
    await db.close()
  }
})
