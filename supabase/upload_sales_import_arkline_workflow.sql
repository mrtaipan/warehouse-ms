create or replace function public.reverse_arkline_sales_import_batch(
  p_batch_id uuid,
  p_actor_email text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target_batch public.upload_sales_import_batches%rowtype;
  lock_key record;
  offset_row public.upload_arkline_pick_offsets%rowtype;
  movement_row public.upload_warehouse_storage_movements%rowtype;
  storage_row public.warehouse_storage%rowtype;
  restored_qty integer;
  restored_total integer := 0;
  actor_email text := nullif(trim(coalesce(p_actor_email, '')), '');
begin
  if not public.arkline_upload_can_manage() then
    raise exception 'Not allowed to manage Arkline uploads';
  end if;

  select * into target_batch
  from public.upload_sales_import_batches
  where id = p_batch_id
  for update;

  if target_batch.id is null or target_batch.group_code <> 'ARKLINE' then
    raise exception 'Arkline upload batch not found';
  end if;
  if target_batch.status = 'pending_settlement' then
    update public.upload_sales_import_batches
    set status = 'cancelled',
        cancelled_by = actor_email,
        cancelled_at = now(),
        settlement_error = null,
        raw_retention_until = now() + interval '7 days',
        updated_at = now()
    where id = p_batch_id;

    return jsonb_build_object('batch_id', p_batch_id, 'status', 'cancelled', 'reversed_qty', 0);
  end if;
  if target_batch.status <> 'posted' then
    raise exception 'Only posted Arkline batches can be reversed';
  end if;
  for lock_key in
    select distinct sku_id, size from public.upload_sales_import_lines
    where batch_id = p_batch_id and included = true and qty > 0
    order by sku_id, size
  loop
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(lock_key.sku_id), pg_catalog.hashtext(lock_key.size));
  end loop;
  for movement_row in
    select * from public.upload_warehouse_storage_movements
    where source_batch_id = p_batch_id
      and source_type = 'upload_arkline_sales_import'
      and movement_type = 'OUT'
    order by created_at desc, id desc
  loop
    restored_qty := abs(movement_row.qty_delta);
    select * into storage_row from public.warehouse_storage
    where id = movement_row.warehouse_storage_id
    for update;

    if storage_row.id is null then
      insert into public.warehouse_storage (
        rack_location_id, sku_id, item_name, size, qty, notes,
        updated_by, updated_at
      ) values (
        movement_row.rack_location_id,
        movement_row.sku_id,
        coalesce(movement_row.item_name_snapshot, movement_row.sku_id, 'Restored Arkline item'),
        movement_row.size,
        restored_qty,
        'Restored from Arkline sales upload ' || target_batch.batch_number,
        actor_email,
        now()
      ) returning * into storage_row;

      insert into public.upload_warehouse_storage_movements (
        source_type, source_batch_id, source_line_id, movement_type,
        warehouse_storage_id, rack_location_id, location_snapshot,
        sku_id, item_name_snapshot, size, qty_before, qty_delta,
        qty_after, storage_row_deleted, reference_number, created_by, notes
      ) values (
        'upload_arkline_sales_import', p_batch_id, movement_row.source_line_id,
        'REVERSE', storage_row.id, movement_row.rack_location_id,
        movement_row.location_snapshot, movement_row.sku_id,
        movement_row.item_name_snapshot, movement_row.size,
        0, restored_qty, storage_row.qty::integer, false,
        movement_row.reference_number, actor_email,
        'Reverse Arkline upload; recreated shelving row'
      );
    else
      insert into public.upload_warehouse_storage_movements (
        source_type, source_batch_id, source_line_id, movement_type,
        warehouse_storage_id, rack_location_id, location_snapshot,
        sku_id, item_name_snapshot, size, qty_before, qty_delta,
        qty_after, storage_row_deleted, reference_number, created_by, notes
      ) values (
        'upload_arkline_sales_import', p_batch_id, movement_row.source_line_id,
        'REVERSE', storage_row.id, movement_row.rack_location_id,
        movement_row.location_snapshot, movement_row.sku_id,
        movement_row.item_name_snapshot, movement_row.size,
        storage_row.qty::integer, restored_qty,
        storage_row.qty::integer + restored_qty, false,
        movement_row.reference_number, actor_email, 'Reverse Arkline shelving sale'
      );

      update public.warehouse_storage
      set qty = qty + restored_qty, updated_by = actor_email, updated_at = now()
      where id = storage_row.id;
    end if;

    restored_total := restored_total + restored_qty;
  end loop;

  for offset_row in
    select * from public.upload_arkline_pick_offsets
    where batch_id = p_batch_id and reversed_at is null
    for update
  loop
    update public.restock_request
    set sales_upload_credited_qty = greatest(0, sales_upload_credited_qty - offset_row.qty)
    where id = offset_row.restock_request_id;

    update public.upload_arkline_pick_offsets
    set reversed_at = now()
    where id = offset_row.id;
  end loop;

  update public.upload_sales_import_batches
  set status = 'reversed',
      reversed_by = actor_email,
      reversed_at = now(),
      updated_at = now()
  where id = p_batch_id;

  return jsonb_build_object(
    'batch_id', p_batch_id,
    'status', 'reversed',
    'reversed_qty', restored_total
  );
end;
$$;

