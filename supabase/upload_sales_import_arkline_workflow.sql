create or replace function public.settle_arkline_sales_import_batch(
  p_batch_id uuid,
  p_actor_email text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target_batch public.upload_sales_import_batches%rowtype;
  lock_key record;
  import_line public.upload_sales_import_lines%rowtype;
  pick_row public.restock_request%rowtype;
  stock_row record;
  pick_credit integer;
  available_credit integer;
  shelf_qty integer;
  remaining_qty integer;
  take_qty integer;
  stock_balance integer;
  total_pick integer := 0;
  total_shelving integer := 0;
  total_skipped integer := 0;
  shortage_lines integer := 0;
  has_shelving_row boolean;
  normalized_sku text;
  normalized_size text;
  actor_email text := nullif(trim(coalesce(p_actor_email, '')), '');
begin
  if current_user <> 'postgres' and not public.arkline_upload_can_manage() then
    raise exception 'Not allowed to manage Arkline uploads';
  end if;

  select * into target_batch
  from public.upload_sales_import_batches
  where id = p_batch_id
  for update;

  if target_batch.id is null or target_batch.group_code not in ('ARKLINE', 'MOB') then
    raise exception 'Arkline upload batch not found';
  end if;
  if target_batch.status = 'posted' and target_batch.settled_at is not null then
    return jsonb_build_object(
      'batch_id', p_batch_id,
      'status', 'posted',
      'pick_offset_qty', target_batch.pick_offset_qty,
      'applied_qty', target_batch.applied_qty,
      'skipped_qty', target_batch.skipped_qty
    );
  end if;
  if target_batch.status <> 'pending_settlement' then
    raise exception 'Only pending Arkline batches can be settled';
  end if;

  actor_email := coalesce(actor_email, target_batch.posted_by, 'ARKLINE AUTO 21:00');

  for lock_key in
    select distinct sku_id, size from public.upload_sales_import_lines
    where batch_id = p_batch_id and included = true and qty > 0
      and regexp_replace(upper(coalesce(sku_id, '')), '[^A-Z0-9]', '', 'g') ~ '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}$'
    order by sku_id, size
  loop
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(lock_key.sku_id), pg_catalog.hashtext(lock_key.size));
  end loop;

  for import_line in
    select * from public.upload_sales_import_lines
    where batch_id = p_batch_id and included = true and qty > 0
      and regexp_replace(upper(coalesce(sku_id, '')), '[^A-Z0-9]', '', 'g') ~ '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}$'
    order by row_number, id
    for update
  loop
    normalized_sku := regexp_replace(upper(coalesce(import_line.sku_id, '')), '[^A-Z0-9]', '', 'g');
    normalized_size := regexp_replace(upper(coalesce(import_line.size, '')), '[^A-Z0-9]', '', 'g');
    if normalized_sku !~ '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}$'
       or normalized_size = ''
       or import_line.order_date is null
       or (target_batch.group_code = 'ARKLINE' and upper(coalesce(import_line.order_status, '')) not in ('PROCESSING', 'SHIPPED'))
       or (target_batch.group_code = 'MOB' and lower(coalesce(import_line.order_status, '')) not in ('packaged', 'ship', 'shipped', 'completed')) then
      raise exception 'Invalid Arkline line %: SKU, size, date and status are required', import_line.row_number;
    end if;
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(normalized_sku), pg_catalog.hashtext(normalized_size));

    select coalesce(sum(storage.qty), 0)::integer, count(*) > 0
    into stock_balance, has_shelving_row
    from public.warehouse_storage storage
    join public.dir_rack_locations location on location.id = storage.rack_location_id
    where upper(coalesce(location.group_code, '')) = 'ARKLINE'
      and upper(coalesce(location.location_type, '')) = 'SHELVING'
      and substring(regexp_replace(upper(coalesce(storage.sku_id, storage.source_variant_code, '')), '[^A-Z0-9]', '', 'g')
        from '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}') = normalized_sku
      and regexp_replace(upper(coalesce(storage.size, '')), '[^A-Z0-9]', '', 'g') = normalized_size;
    pick_credit := 0;
    for pick_row in
      select request.*
      from public.restock_request request
      where request.source_type = 'ARKLINE'
        and request.request_status = 'completed'
        and (request.completed_at at time zone 'Asia/Jakarta')::date = import_line.order_date
        and substring(
          regexp_replace(upper(coalesce(nullif(trim(request.source_sku_id), ''), request.search_term)), '[^A-Z0-9]', '', 'g')
          from '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}'
        ) = normalized_sku
        and regexp_replace(upper(coalesce(request.size, '')), '[^A-Z0-9]', '', 'g') = normalized_size
        and request.sales_upload_credited_qty < least(request.qty, coalesce(request.fulfilled_qty, request.qty))
      order by request.completed_at, request.id
      for update of request
    loop
      exit when pick_credit >= import_line.qty;
      available_credit := greatest(
        0,
        least(pick_row.qty, coalesce(pick_row.fulfilled_qty, pick_row.qty))
          - pick_row.sales_upload_credited_qty
      );
      take_qty := least(import_line.qty - pick_credit, available_credit);
      if take_qty <= 0 then continue; end if;

      update public.restock_request
      set sales_upload_credited_qty = sales_upload_credited_qty + take_qty
      where id = pick_row.id;

      insert into public.upload_arkline_pick_offsets (
        batch_id, line_id, restock_request_id, qty
      ) values (
        p_batch_id, import_line.id, pick_row.id, take_qty
      );

      pick_credit := pick_credit + take_qty;
    end loop;

    shelf_qty := import_line.qty - pick_credit;
    remaining_qty := shelf_qty;

    for stock_row in
      select storage.id, storage.rack_location_id, storage.sku_id,
        storage.item_name, storage.size, storage.qty,
        jsonb_build_object(
          'rack_location_id', location.id,
          'location_type', location.location_type,
          'location_id', location.location_id,
          'location_code', location.location_code,
          'sub_location', location.sub_location,
          'location_name', location.location_name,
          'group_code', location.group_code
        ) as location_snapshot
      from public.warehouse_storage storage
      join public.dir_rack_locations location on location.id = storage.rack_location_id
      where upper(coalesce(location.group_code, '')) = 'ARKLINE'
        and upper(coalesce(location.location_type, '')) = 'SHELVING'
        and storage.qty > 0
        and substring(regexp_replace(upper(coalesce(storage.sku_id, storage.source_variant_code, '')), '[^A-Z0-9]', '', 'g')
          from '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}') = normalized_sku
        and regexp_replace(upper(coalesce(storage.size, '')), '[^A-Z0-9]', '', 'g') = normalized_size
      order by storage.created_at, storage.id
      for update of storage
    loop
      exit when remaining_qty <= 0;
      take_qty := least(remaining_qty, stock_row.qty::integer);
      if take_qty <= 0 then continue; end if;

      insert into public.upload_warehouse_storage_movements (
        source_type, source_batch_id, source_line_id, movement_type,
        warehouse_storage_id, rack_location_id, location_snapshot,
        sku_id, item_name_snapshot, size, qty_before, qty_delta,
        qty_after, storage_row_deleted, reference_number, created_by, notes
      ) values (
        'upload_arkline_sales_import', p_batch_id, import_line.id, 'OUT',
        stock_row.id, stock_row.rack_location_id, stock_row.location_snapshot,
        stock_row.sku_id, stock_row.item_name, stock_row.size,
        stock_row.qty::integer, -take_qty, stock_row.qty::integer - take_qty,
        false, import_line.order_number, actor_email, 'Arkline shelving sales'
      );

      update public.warehouse_storage
      set qty = qty - take_qty, updated_by = actor_email, updated_at = now()
      where id = stock_row.id;

      remaining_qty := remaining_qty - take_qty;
    end loop;

    if remaining_qty > 0 then
      select storage.id, storage.rack_location_id, storage.sku_id,
        storage.item_name, storage.size, storage.qty,
        jsonb_build_object(
          'rack_location_id', location.id,
          'location_type', location.location_type,
          'location_id', location.location_id,
          'location_code', location.location_code,
          'sub_location', location.sub_location,
          'location_name', location.location_name,
          'group_code', location.group_code
        ) as location_snapshot
      into stock_row
      from public.warehouse_storage storage
      join public.dir_rack_locations location on location.id = storage.rack_location_id
      where upper(coalesce(location.group_code, '')) = 'ARKLINE'
        and upper(coalesce(location.location_type, '')) = 'SHELVING'
        and substring(regexp_replace(upper(coalesce(storage.sku_id, storage.source_variant_code, '')), '[^A-Z0-9]', '', 'g')
          from '^ARK[0-9]{2}[A-Z]{3}[0-9]{3}') = normalized_sku
        and regexp_replace(upper(coalesce(storage.size, '')), '[^A-Z0-9]', '', 'g') = normalized_size
      order by storage.qty asc, storage.created_at, storage.id
      limit 1
      for update of storage;

      if stock_row.id is not null then
        insert into public.upload_warehouse_storage_movements (
          source_type, source_batch_id, source_line_id, movement_type,
          warehouse_storage_id, rack_location_id, location_snapshot,
          sku_id, item_name_snapshot, size, qty_before, qty_delta,
          qty_after, storage_row_deleted, reference_number, created_by, notes
        ) values (
          'upload_arkline_sales_import', p_batch_id, import_line.id, 'OUT',
          stock_row.id, stock_row.rack_location_id, stock_row.location_snapshot,
          stock_row.sku_id, stock_row.item_name, stock_row.size,
          stock_row.qty::integer, -remaining_qty,
          stock_row.qty::integer - remaining_qty, false,
          import_line.order_number, actor_email, 'Arkline shelving sales deficit'
        );
        update public.warehouse_storage
        set qty = qty - remaining_qty, updated_by = actor_email, updated_at = now()
        where id = stock_row.id;
        remaining_qty := 0;
      end if;
    end if;

    update public.upload_sales_import_lines
    set pick_offset_qty = pick_credit,
        applied_qty = shelf_qty - remaining_qty,
        skipped_qty = remaining_qty,
        available_qty_snapshot = greatest(0, stock_balance),
        balance_after_snapshot = case when has_shelving_row then stock_balance - shelf_qty else null end,
        exclusion_reason = null
    where id = import_line.id;

    total_pick := total_pick + pick_credit;
    total_shelving := total_shelving + shelf_qty - remaining_qty;
    total_skipped := total_skipped + remaining_qty;
    if has_shelving_row and stock_balance - shelf_qty < 0 then
      shortage_lines := shortage_lines + 1;
    end if;
  end loop;

  if target_batch.group_code = 'MOB' then
    return jsonb_build_object(
      'batch_id', p_batch_id,
      'status', 'pending_settlement',
      'pick_offset_qty', total_pick,
      'applied_qty', total_shelving,
      'skipped_qty', total_skipped,
      'shortage_line_count', shortage_lines
    );
  end if;

  update public.upload_sales_import_batches
  set status = 'posted',
      settled_at = now(),
      settled_by = coalesce(nullif(trim(coalesce(p_actor_email, '')), ''), 'ARKLINE AUTO 21:00'),
      settlement_error = null,
      raw_retention_until = now() + interval '7 days',
      pick_offset_qty = total_pick,
      applied_qty = total_shelving,
      skipped_qty = total_skipped,
      shortage_line_count = shortage_lines,
      updated_at = now()
  where id = p_batch_id;

  return jsonb_build_object(
    'batch_id', p_batch_id,
    'status', 'posted',
    'pick_offset_qty', total_pick,
    'applied_qty', total_shelving,
    'skipped_qty', total_skipped,
    'shortage_line_count', shortage_lines
  );
end;
$$;

