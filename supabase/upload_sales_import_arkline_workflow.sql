  p_actor_email text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target_batch public.upload_sales_import_batches%rowtype;
  lock_key record;
  import_line public.upload_sales_import_lines%rowtype;
  stock_row record;
  remaining_qty integer;
