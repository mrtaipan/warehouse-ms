begin;

create table if not exists public.packaging_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0
);

create table if not exists public.packaging_items (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.packaging_categories(id),
  name text not null unique,
  unit text not null check (unit in ('pcs', 'roll', 'pack', 'sheet')),
  pieces_per_unit integer check (pieces_per_unit > 0),
  qty integer not null default 0 check (qty >= 0),
  reorder_mode text not null default 'FIXED' check (reorder_mode in ('FIXED', 'CONSUMPTION')),
  reorder_point_qty integer check (reorder_point_qty >= 0),
  coverage_days integer not null default 14 check (coverage_days between 1 and 365),
  active boolean not null default true,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.packaging_movements (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.packaging_items(id) on delete restrict,
  movement_type text not null check (movement_type in ('OPENING', 'IN', 'OUT', 'ADJUSTMENT')),
  qty_change integer not null check (qty_change <> 0),
  qty_after integer not null check (qty_after >= 0),
  note text not null check (length(btrim(note)) > 0),
  created_by uuid not null,
  created_at timestamptz not null default now(),
  check (movement_type <> 'IN' or qty_change > 0),
  check (movement_type <> 'OUT' or qty_change < 0),
  check (movement_type <> 'OPENING' or qty_change > 0)
);

create index if not exists packaging_movements_item_date_idx
  on public.packaging_movements(item_id, created_at desc);

alter table public.packaging_categories enable row level security;
alter table public.packaging_items enable row level security;
alter table public.packaging_movements enable row level security;
grant select on public.packaging_categories, public.packaging_items, public.packaging_movements to authenticated;

drop policy if exists packaging_categories_read on public.packaging_categories;
create policy packaging_categories_read on public.packaging_categories for select to authenticated
  using (public.reqc_has_permission('storage.location.view'));
drop policy if exists packaging_items_read on public.packaging_items;
create policy packaging_items_read on public.packaging_items for select to authenticated
  using (public.reqc_has_permission('storage.location.view'));
drop policy if exists packaging_movements_read on public.packaging_movements;
create policy packaging_movements_read on public.packaging_movements for select to authenticated
  using (public.reqc_has_permission('storage.location.view'));

create or replace function public.record_packaging_movement(
  p_item_id bigint, p_movement_type text, p_qty integer, p_note text
) returns public.packaging_movements
language plpgsql security definer set search_path = '' as $$
declare v_item public.packaging_items%rowtype;
  v_change integer;
  v_movement public.packaging_movements%rowtype;
begin
  if (select auth.uid()) is null or not public.reqc_has_permission('storage.location.edit') then
    raise exception 'Not allowed to change packaging stock';
  end if;
  if p_movement_type not in ('OPENING', 'IN', 'OUT', 'ADJUSTMENT') or p_qty is null or p_qty = 0
    or nullif(btrim(p_note), '') is null then
    raise exception 'Movement type, nonzero quantity, and note are required';
  end if;
  select * into v_item from public.packaging_items where id = p_item_id and active for update;
  if not found then raise exception 'Packaging item not found'; end if;
  if p_movement_type = 'OPENING' and exists (
    select 1 from public.packaging_movements where item_id = p_item_id
  ) then raise exception 'Opening stock can only be recorded before other movements'; end if;
  v_change := case when p_movement_type = 'OUT' then -abs(p_qty)
    when p_movement_type in ('OPENING', 'IN') then abs(p_qty) else p_qty end;
  if v_item.qty + v_change < 0 then raise exception 'Insufficient packaging stock'; end if;
  update public.packaging_items set qty = qty + v_change, updated_at = now() where id = p_item_id;
  insert into public.packaging_movements(item_id, movement_type, qty_change, qty_after, note, created_by)
  values (p_item_id, p_movement_type, v_change, v_item.qty + v_change, btrim(p_note), (select auth.uid()))
  returning * into v_movement;
  return v_movement;
end;
$$;
revoke all on function public.record_packaging_movement(bigint,text,integer,text) from public, anon;
grant execute on function public.record_packaging_movement(bigint,text,integer,text) to authenticated;

create or replace function public.set_packaging_reorder(
  p_item_id bigint, p_mode text, p_point integer, p_days integer
) returns public.packaging_items
language plpgsql security definer set search_path = '' as $$
declare v_item public.packaging_items%rowtype;
begin
  if (select auth.uid()) is null or not public.reqc_has_permission('storage.location.edit') then
    raise exception 'Not allowed to change packaging reorder settings';
  end if;
  if p_mode not in ('FIXED', 'CONSUMPTION') or p_point < 0 or p_days not between 1 and 365
    or (p_mode = 'FIXED' and p_point is null) then
    raise exception 'Invalid reorder settings';
  end if;
  update public.packaging_items set reorder_mode = p_mode,
    reorder_point_qty = case when p_mode = 'FIXED' then p_point else null end,
    coverage_days = p_days, updated_at = now()
  where id = p_item_id and active returning * into v_item;
  if not found then raise exception 'Packaging item not found'; end if;
  return v_item;
end;
$$;
revoke all on function public.set_packaging_reorder(bigint,text,integer,integer) from public, anon;
grant execute on function public.set_packaging_reorder(bigint,text,integer,integer) to authenticated;

create or replace function public.packaging_outbound_30d()
returns table(item_id bigint, out_qty bigint)
language plpgsql stable security definer set search_path = '' as $$
begin
  if (select auth.uid()) is null or not public.reqc_has_permission('storage.location.view') then
    raise exception 'Not allowed to read packaging consumption';
  end if;
  return query
    select movement.item_id, sum(-movement.qty_change)::bigint
    from public.packaging_movements movement
    where movement.movement_type = 'OUT'
      and movement.created_at >= now() - interval '30 days'
    group by movement.item_id;
end;
$$;
revoke all on function public.packaging_outbound_30d() from public, anon;
grant execute on function public.packaging_outbound_30d() to authenticated;

