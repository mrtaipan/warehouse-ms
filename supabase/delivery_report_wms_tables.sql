-- Delivery Report tables migrated into the main WMS Supabase project.
-- Transactional tables are structure-only at this stage.
-- Static/master tables below are seeded from the legacy Delivery Report project.

create table if not exists public.delivery_courier (
  id bigint generated by default as identity primary key,
  nama text not null unique,
  is_active boolean default true
);

create table if not exists public.delivery_channel (
  id bigint generated by default as identity primary key,
  nama text not null unique,
  is_active boolean default true
);

create table if not exists public.delivery_category (
  id bigint generated by default as identity primary key,
  nama text not null unique,
  is_active boolean default true
);

create table if not exists public.delivery_courier_subclass (
  id bigint generated by default as identity primary key,
  courier_name text not null references public.delivery_courier(nama) on update cascade on delete restrict,
  courier_service text,
  is_active boolean default true
);

create table if not exists public.delivery_barcode_rules (
  id bigint generated by default as identity primary key,
  is_active boolean not null default true,
  rule_type text not null,
  pattern text,
  match_type text,
  result_value text references public.delivery_courier(nama) on update cascade on delete set null,
  priority smallint
);

create table if not exists public.delivery_order (
  id bigint generated by default as identity primary key,
  delivery_date date not null,
  delivery_category text,
  group_order text,
  channel text,
  part_no smallint,
  courier text,
  quantity integer,
  keterangan text,
  updated_time timestamp with time zone default now(),
  created_by text,
  updated_by text
);

create table if not exists public.delivery_barcode (
  barcode text primary key,
  timestamp_delivery timestamp with time zone,
  group_order text,
  courier text,
  is_defined boolean,
  timestamp_packing timestamp with time zone,
  packing_team text,
  is_packed boolean,
  is_delivered boolean,
  delivery_scanned_by text,
  packing_scanned_by text
);

create table if not exists public.delivery_retur_reason (
  id bigint generated by default as identity primary key,
  name text not null,
  reasoning_type text not null,
  is_active boolean default true
);

create table if not exists public.delivery_retur_action (
  id bigint generated by default as identity primary key,
  name text not null,
  requires_return boolean,
  requires_refund_value boolean,
  replacement_required boolean,
  is_active boolean default true
);

create table if not exists public.delivery_error_retur_cases (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone default now(),
  tanggal_pengajuan timestamp with time zone,
  batas_tanggal_retur timestamp with time zone,
  group_order text,
  internal_external text,
  kode_kejadian text not null unique,
  order_id text,
  nama_customer text,
  no_handphone text,
  no_resi_pengiriman text references public.delivery_barcode(barcode) on update cascade on delete restrict,
  nomor_tim text,
  courier_name text references public.delivery_courier(nama) on update cascade on delete restrict,
  courier_service text,
  retur_reason text,
  retur_action text,
  produk_diretur text,
  produk_pengganti text,
  ongkir_masuk numeric,
  ongkir_keluar numeric,
  nilai_refund_kompensasi numeric,
  keterangan_tambahan text,
  status_barang text default 'Pending',
  total_retur numeric,
  alamat text,
  note_konsumen text,
  need_prioritized boolean default false,
  created_by text,
  updated_by text
);

create table if not exists public.delivery_order_issue (
  id bigint generated by default as identity primary key,
  name text,
  is_active boolean default true
);

create table if not exists public.delivery_order_handling (
  id bigint generated by default as identity primary key,
  name text,
  is_active boolean default true,
  is_pending boolean,
  add_cost boolean
);

create table if not exists public.delivery_order_issue_cases (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone default now(),
  created_by text,
  updated_by text,
  group_order text,
  order_id text,
  nama text,
  no_hp numeric,
  produk_bermasalah text,
  alasan_bermasalah text,
  tindak_lanjut text,
  produk_pengganti text,
  tim text,
  biaya_timbul numeric,
  keterangan text
);

create table if not exists public.delivery_resi_manual (
  id bigint generated by default as identity,
  created_at timestamp with time zone not null default now(),
  resi_manual text not null,
  nama text,
  no_hp text,
  alamat text,
  barang text,
  harga_paket text,
  nama_courier text references public.delivery_courier(nama) on update cascade on delete restrict,
  layanan_courier text,
  keterangan text,
  primary key (id, resi_manual)
);

