do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'delivery_courier',
    'delivery_channel',
    'delivery_category',
    'delivery_courier_subclass',
    'delivery_barcode_rules',
    'delivery_order',
    'delivery_barcode',
    'delivery_retur_reason',
    'delivery_retur_action',
    'delivery_error_retur_cases',
    'delivery_order_issue',
    'delivery_order_handling',
    'delivery_order_issue_cases',
    'delivery_resi_manual'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, public, authenticated, service_role', table_name);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', table_name);
    execute format('grant select, insert, update, delete on table public.%I to service_role', table_name);

    execute format('drop policy if exists %I on public.%I', 'delivery authenticated select', table_name);
    execute format('drop policy if exists %I on public.%I', 'delivery authenticated insert', table_name);
    execute format('drop policy if exists %I on public.%I', 'delivery authenticated update', table_name);
    execute format('drop policy if exists %I on public.%I', 'delivery authenticated delete', table_name);

    execute format('create policy %I on public.%I for select to authenticated using ((select auth.uid()) is not null)', 'delivery authenticated select', table_name);
    execute format('create policy %I on public.%I for insert to authenticated with check ((select auth.uid()) is not null)', 'delivery authenticated insert', table_name);
    execute format('create policy %I on public.%I for update to authenticated using ((select auth.uid()) is not null) with check ((select auth.uid()) is not null)', 'delivery authenticated update', table_name);
    execute format('create policy %I on public.%I for delete to authenticated using ((select auth.uid()) is not null)', 'delivery authenticated delete', table_name);
  end loop;
end $$;

