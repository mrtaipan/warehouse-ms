-- One-time correction: align inbound IDs 30-33 with GRNs 029-032.
-- Run as one transaction. The guards make a repeated run fail safely.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';

lock table public.inbound in access exclusive mode;
lock table public.warehouse_return_koli_reversals in access exclusive mode;

do $$
declare fk record;
begin
  if exists (select 1 from public.inbound where id = 29)
     or (select count(*) from public.inbound where id between 30 and 33) <> 4
     or (select max(id) from public.inbound) <> 33
     or (select array_agg(grn_number order by id) from public.inbound where id between 30 and 33)
        is distinct from array['#029-X2026', '#030-XI2026', '#031-XI2026', '#032-XI2026']::text[]
     or (select count(*) from pg_constraint where contype = 'f' and confrelid = 'public.inbound'::regclass) <> 10
     or exists (select 1 from pg_constraint where contype = 'f' and confrelid = 'public.inbound'::regclass and condeferrable) then
    raise exception 'Inbound records or foreign keys changed; aborting ID correction';
  end if;

  for fk in
    select conrelid::regclass as relation_name, conname
    from pg_constraint
    where contype = 'f' and confrelid = 'public.inbound'::regclass
  loop
    execute format('alter table %s alter constraint %I deferrable initially deferred', fk.relation_name, fk.conname);
  end loop;
end $$;

alter table public.inbound alter column id set generated by default;
set constraints all deferred;

do $$
declare old_id integer; table_name text; affected integer;
begin
  for old_id in 30..33 loop
    update public.inbound set id = old_id - 1 where id = old_id;
    get diagnostics affected = row_count;
    if affected <> 1 then
      raise exception 'Expected one inbound row for ID %, got %', old_id, affected;
    end if;
  end loop;

  -- The sample breakdown FK has ON UPDATE CASCADE, so do not shift it twice.
  foreach table_name in array array[
    'inbound_receiving', 'inbound_unload', 'pl_general_photos', 'pl_packing_items',
    'pl_receiving', 'pl_size_breakdown', 'qc_confirm', 'qc_items',
    'warehouse_returns', 'warehouse_return_koli_reversals'
  ] loop
    for old_id in 30..33 loop
      execute format('update public.%I set inbound_id = $1 where inbound_id = $2', table_name)
        using old_id - 1, old_id;
    end loop;
  end loop;
end $$;

set constraints all immediate;
alter table public.inbound alter column id set generated always;

do $$
declare fk record;
begin
  for fk in
    select conrelid::regclass as relation_name, conname
    from pg_constraint
    where contype = 'f' and confrelid = 'public.inbound'::regclass
  loop
    execute format('alter table %s alter constraint %I not deferrable initially immediate', fk.relation_name, fk.conname);
  end loop;

  if exists (select 1 from public.inbound where id = 33)
     or (select array_agg(grn_number order by id) from public.inbound where id between 29 and 32)
        is distinct from array['#029-X2026', '#030-XI2026', '#031-XI2026', '#032-XI2026']::text[]
     or exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'inbound' and column_name = 'id'
         and identity_generation <> 'ALWAYS'
     ) then
    raise exception 'Inbound ID correction verification failed';
  end if;
end $$;

-- This is transactional, unlike setval(), and makes the next generated ID 33.
alter sequence public.inbound_id_seq restart with 33;
commit;
