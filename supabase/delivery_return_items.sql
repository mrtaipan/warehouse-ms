  for select to authenticated using ((select auth.uid()) is not null);

drop policy if exists delivery_return_items_authenticated_insert on public.delivery_return_items;
create policy delivery_return_items_authenticated_insert on public.delivery_return_items
  for insert to authenticated with check ((select auth.uid()) is not null);

drop policy if exists delivery_return_items_authenticated_update on public.delivery_return_items;
create policy delivery_return_items_authenticated_update on public.delivery_return_items
  for update to authenticated
  using ((select auth.uid()) is not null)
  with check ((select auth.uid()) is not null);

comment on table public.delivery_return_items is
  'Per-product customer return decisions. STORED means accepted for stock; route_status tracks physical placement.';
