-- One decision row per returned product line and outcome.
-- The source case remains in delivery_error_retur_cases; no QC/PO row is invented.
create table if not exists public.delivery_return_items (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.delivery_error_retur_cases(id) on update cascade on delete restrict,
  source_line_no integer not null check (source_line_no > 0),
  group_code text not null check (group_code in ('ARKLINE', 'MOB', 'OI')),
  sku text null,
  product_name text not null check (btrim(product_name) <> ''),
  size text null,
  expected_qty integer not null check (expected_qty > 0),
  outcome text not null check (outcome in ('STORED', 'REJECT', 'LOST')),
  qty integer not null check (qty > 0 and qty <= expected_qty),
  route_status text not null default 'PENDING',
  reason text null,
  notes text null,
  created_at timestamptz not null default now(),
  created_by text null,
  updated_at timestamptz not null default now(),
  updated_by text null,
  handled_at timestamptz null,
  handled_by text null,
  constraint delivery_return_items_case_line_outcome_key unique (case_id, source_line_no, outcome),
  constraint delivery_return_items_route_status_check check (
    (outcome = 'STORED' and route_status in ('PENDING', 'WAITING_SHELVING', 'STORED')) or
    (outcome = 'REJECT' and route_status in ('PENDING', 'PENDING_ARRANGEMENT', 'RETURN_BATCHED', 'REJECTION_STORED', 'KOLI_ASSIGNED')) or
    (outcome = 'LOST' and route_status in ('PENDING', 'RECORDED'))
  ),
  constraint delivery_return_items_lost_reason_check check (
    outcome <> 'LOST' or nullif(btrim(reason), '') is not null
  )
);

create index if not exists delivery_return_items_case_line_idx
  on public.delivery_return_items (case_id, source_line_no);

create index if not exists delivery_return_items_worklist_idx
  on public.delivery_return_items (group_code, outcome, route_status, created_at);

create or replace function public.validate_delivery_return_item_allocation()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  case_group text;
  prior_expected_qty integer;
  prior_allocated_qty bigint;
begin
  select upper(btrim(group_order)) into case_group
  from public.delivery_error_retur_cases
  where id = new.case_id
  for update;

  if case_group is distinct from new.group_code then
    raise exception 'Return item group must match its case group';
  end if;

  select min(expected_qty), coalesce(sum(qty), 0)
  into prior_expected_qty, prior_allocated_qty
  from public.delivery_return_items
  where case_id = new.case_id
    and source_line_no = new.source_line_no
    and id is distinct from new.id;

  if prior_expected_qty is not null and prior_expected_qty <> new.expected_qty then
    raise exception 'Expected quantity must match all decisions for the same return product';
  end if;

  if prior_allocated_qty + new.qty > new.expected_qty then
    raise exception 'Return decisions exceed the expected quantity for this product';
  end if;

  return new;
end;
$$;

drop trigger if exists delivery_return_items_validate_allocation on public.delivery_return_items;
create trigger delivery_return_items_validate_allocation
  before insert or update on public.delivery_return_items
  for each row execute function public.validate_delivery_return_item_allocation();

alter table public.delivery_return_items enable row level security;

