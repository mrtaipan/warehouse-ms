-- Temporary sample breakdown workflow.
-- Samples remain as source rows in inbound_unload. Product details and QC
-- result splits are stored as child rows so QC task history stays intact.

begin;

alter table public.inbound_unload
  add column if not exists variant_name text,
  add column if not exists product_model_id bigint,
  add column if not exists product_model_variant_id bigint,
  add column if not exists is_product_temporary boolean not null default false,
  add column if not exists sample_resolved_at timestamp with time zone null,
  add column if not exists sample_resolved_by text null;

do $$
begin
  if not exists (
    select 1
    from information_schema.table_constraints
    where table_schema = 'public'
      and table_name = 'inbound_unload'
      and constraint_name = 'inbound_unload_product_model_id_fkey'
  ) then
    alter table public.inbound_unload
      add constraint inbound_unload_product_model_id_fkey
      foreign key (product_model_id)
      references public.dir_product_models(id)
      on delete set null;
  end if;

  if not exists (
    select 1
    from information_schema.table_constraints
    where table_schema = 'public'
      and table_name = 'inbound_unload'
      and constraint_name = 'inbound_unload_product_model_variant_id_fkey'
  ) then
    alter table public.inbound_unload
      add constraint inbound_unload_product_model_variant_id_fkey
      foreign key (product_model_variant_id)
      references public.dir_product_model_variants(id)
      on delete set null;
  end if;
end $$;

create index if not exists inbound_unload_product_model_id_idx
  on public.inbound_unload (product_model_id);

create index if not exists inbound_unload_product_model_variant_id_idx
  on public.inbound_unload (product_model_variant_id);

update public.inbound_unload
set
  is_product_temporary = true,
  model_name = coalesce(nullif(model_name, ''), 'TEMPORARY SAMPLE'),
  variant_name = coalesce(nullif(variant_name, ''), 'TEMPORARY'),
  updated_at = now()
where coalesce(is_sample, false) = true
  and (
    product_model_id is null
    or product_model_variant_id is null
    or upper(coalesce(model_name, '')) in ('', 'SAMPLE', 'TEMPORARY SAMPLE')
  );

create table if not exists public.inbound_sample_model_breakdowns (
  id bigint generated by default as identity primary key,
  inbound_unload_id bigint not null references public.inbound_unload(id) on update cascade on delete cascade,
  inbound_id bigint null references public.inbound(id) on update cascade on delete cascade,
  brand_id bigint null references public.dir_brands(id) on update cascade on delete set null,
  category_id bigint null references public.dir_categories(id) on update cascade on delete set null,
  product_model_id bigint null references public.dir_product_models(id) on update cascade on delete set null,
  product_model_variant_id bigint null references public.dir_product_model_variants(id) on update cascade on delete set null,
  model_name text not null,
  variant_name text null,
  photo_url text null,
  qty integer not null default 0 check (qty >= 0),
  created_by text null,
  updated_by text null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create index if not exists inbound_sample_model_breakdowns_unload_idx
