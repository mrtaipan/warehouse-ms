  qc_item_id bigint not null references public.qc_items(id) on update cascade on delete cascade,
  sample_breakdown_id bigint not null references public.inbound_sample_model_breakdowns(id) on update cascade on delete cascade,
  qty_a integer not null default 0 check (qty_a >= 0),
  qty_b integer not null default 0 check (qty_b >= 0),
  qty_c integer not null default 0 check (qty_c >= 0),
