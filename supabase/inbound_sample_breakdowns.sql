create or replace function public.validate_qc_sample_breakdown()
returns trigger
language plpgsql
as $$
declare
  qc_row record;
  sample_row record;
  split_total integer;
  model_split_total integer;
  checked_total integer;
begin
  select
    qi.id,
    qi.inbound_unload_id,
    coalesce(qi.qty_a, 0) as qty_a,
    coalesce(qi.qty_b, 0) as qty_b,
    coalesce(qi.qty_c, 0) as qty_c
  into qc_row
  from public.qc_items qi
  where qi.id = new.qc_item_id;

  if not found then
    raise exception 'QC item % was not found.', new.qc_item_id;
  end if;

  select
    b.id,
    b.inbound_unload_id,
    b.qty
  into sample_row
  from public.inbound_sample_model_breakdowns b
  where b.id = new.sample_breakdown_id;

  if not found then
    raise exception 'Sample breakdown % was not found.', new.sample_breakdown_id;
  end if;

  if qc_row.inbound_unload_id <> sample_row.inbound_unload_id then
    raise exception 'QC item % and sample breakdown % do not belong to the same sample source.', new.qc_item_id, new.sample_breakdown_id;
  end if;

  checked_total := qc_row.qty_a + qc_row.qty_b + qc_row.qty_c;

  select coalesce(sum(qsb.qty_a + qsb.qty_b + qsb.qty_c), 0)
  into split_total
  from public.qc_sample_breakdowns qsb
  where qsb.qc_item_id = new.qc_item_id
    and qsb.id <> coalesce(new.id, 0);

  split_total := split_total + new.qty_a + new.qty_b + new.qty_c;

  if split_total > checked_total then
    raise exception 'QC sample split total % cannot exceed checked qty % for QC item %.', split_total, checked_total, new.qc_item_id;
  end if;

  select coalesce(sum(qsb.qty_a + qsb.qty_b + qsb.qty_c), 0)
  into model_split_total
  from public.qc_sample_breakdowns qsb
  where qsb.sample_breakdown_id = new.sample_breakdown_id
    and qsb.id <> coalesce(new.id, 0);

  model_split_total := model_split_total + new.qty_a + new.qty_b + new.qty_c;

  if model_split_total > coalesce(sample_row.qty, 0) then
    raise exception 'QC sample split total % cannot exceed model breakdown qty % for sample breakdown %.', model_split_total, sample_row.qty, new.sample_breakdown_id;
  end if;

  new.updated_at := now();
  return new;
end $$;

drop trigger if exists trg_validate_qc_sample_breakdown
  on public.qc_sample_breakdowns;

create trigger trg_validate_qc_sample_breakdown
before insert or update on public.qc_sample_breakdowns
for each row
execute function public.validate_qc_sample_breakdown();

create or replace view public.inbound_sample_resolution_status as
with model_totals as (
  select
    inbound_unload_id,
    count(*) as model_row_count,
    coalesce(sum(qty), 0) as model_breakdown_qty
  from public.inbound_sample_model_breakdowns
  group by inbound_unload_id
),
qc_totals as (
  select
    inbound_unload_id,
    count(*) as qc_item_count,
    coalesce(sum(coalesce(qty_a, 0) + coalesce(qty_b, 0) + coalesce(qty_c, 0)), 0) as qc_checked_qty
  from public.qc_items
  group by inbound_unload_id
),
qc_split_totals as (
  select
    b.inbound_unload_id,
    count(*) as qc_split_row_count,
    coalesce(sum(coalesce(qsb.qty_a, 0) + coalesce(qsb.qty_b, 0) + coalesce(qsb.qty_c, 0)), 0) as qc_split_qty
  from public.qc_sample_breakdowns qsb
  join public.inbound_sample_model_breakdowns b
    on b.id = qsb.sample_breakdown_id
  group by b.inbound_unload_id
)
select
  iu.id as inbound_unload_id,
  iu.inbound_id,
  iu.koli_sequence,
  iu.qty as sample_qty,
  coalesce(iu.is_product_temporary, false) as is_product_temporary,
  coalesce(mt.model_row_count, 0) as model_row_count,
  coalesce(mt.model_breakdown_qty, 0) as model_breakdown_qty,
  coalesce(qt.qc_item_count, 0) as qc_item_count,
  coalesce(qt.qc_checked_qty, 0) as qc_checked_qty,
  coalesce(qst.qc_split_row_count, 0) as qc_split_row_count,
  coalesce(qst.qc_split_qty, 0) as qc_split_qty,
  coalesce(mt.model_breakdown_qty, 0) = coalesce(iu.qty, 0) as is_model_resolved,
  (
    coalesce(qt.qc_checked_qty, 0) = 0
    or coalesce(qst.qc_split_qty, 0) = coalesce(qt.qc_checked_qty, 0)
  ) as is_qc_split_resolved,
  (
    coalesce(mt.model_breakdown_qty, 0) = coalesce(iu.qty, 0)
    and (
      coalesce(qt.qc_checked_qty, 0) = 0
      or coalesce(qst.qc_split_qty, 0) = coalesce(qt.qc_checked_qty, 0)
    )
  ) as is_sample_resolved
from public.inbound_unload iu
left join model_totals mt
  on mt.inbound_unload_id = iu.id
left join qc_totals qt
  on qt.inbound_unload_id = iu.id
left join qc_split_totals qst
  on qst.inbound_unload_id = iu.id
where coalesce(iu.is_sample, false) = true;

